"""Starting characters for DoD.

1. Vanilla characters are kept only for tags that are still "themselves" in DoD: the DoD
   country has the same capital state as vanilla. Tags with a hand-written DoD ruler in
   common/history/characters/dod_characters.txt never keep vanilla characters. Every other
   country gets rulers generated by the game. (The mod replaces vanilla's history/characters.)
2. The Vic2 mod's 309 starting generals and admirals (history/units) become Vic3 commanders,
   with their Vic2 personality and background turned into Vic3 traits.

Usage: py tools/vic3_characters.py <vic3_game_dir> <vic2_mod_dir>
Writes DoD_Vic3/common/history/characters/00_dod_vanilla_characters.txt and dod_commanders.txt
"""
import collections, re, sys
from pathlib import Path

V3, V2 = Path(sys.argv[1]), Path(sys.argv[2])
ROOT = Path(__file__).resolve().parent.parent
MOD = ROOT / "DoD_Vic3"
OUTDIR = MOD / "common/history/characters"

cd = (MOD / "common/country_definitions/dod_countries.txt").read_text(encoding="utf-8-sig")
dod_cap = {m.group(1): c.group(1) for m in re.finditer(r"^(\w{3}) = \{(.*?)^\}", cd, re.S | re.M)
           if (c := re.search(r"^\s*capital = (STATE_\w+)", m.group(2), re.M))}
van_cap = {}
for f in (V3 / "common/country_definitions").glob("*.txt"):
    for m in re.finditer(r"^(\w{3})\s*=\s*\{(.*?)^\}", f.read_text(encoding="utf-8-sig"), re.S | re.M):
        c = re.search(r"capital\s*=\s*(STATE_\w+)", m.group(2))
        if c:
            van_cap[m.group(1)] = c.group(1)
hand = set(re.findall(r"c:(\w+) \?=", (OUTDIR / "dod_characters.txt").read_text(encoding="utf-8-sig")))
keep = {t for t, c in van_cap.items() if dod_cap.get(t) == c and t not in hand}

# ---------- 1. filtered vanilla characters ----------
out = ["# Generated by tools/vic3_characters.py: vanilla characters, kept only for countries whose",
       "# DoD capital is the same as in vanilla. Kept tags: " + " ".join(sorted(keep)), "CHARACTERS = {"]
kept_blocks = 0
for f in sorted((V3 / "common/history/characters").glob("*.txt")):
    t = f.read_text(encoding="utf-8-sig")
    body = t[t.index("{") + 1:t.rindex("}")]
    # split top-level c:TAG blocks by brace depth
    depth, start, tag = 0, None, None
    i = 0
    while i < len(body):
        ch = body[i]
        if depth == 0:
            m = re.compile(r"c:(\w+)\s*\??=\s*\{").match(body, i)
            if m:
                tag, start, depth, i = m.group(1), i, 1, m.end()
                continue
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0 and start is not None:
                if tag in keep:
                    out.append("\t" + body[start:i + 1].strip())
                    kept_blocks += 1
                start = None
        i += 1
out.append("}")
(OUTDIR / "00_dod_vanilla_characters.txt").write_text("\n".join(out) + "\n", encoding="utf-8-sig")

# ---------- 2. Vic2 generals and admirals ----------
PERSONALITY = {
    "harsh": "cruel", "vicious": "cruel", "relentless": "persistent", "aggressive": "reckless",
    "hellbent": "reckless", "unsound": "reckless", "reserved": "reserved", "earnest": "honorable",
    "inspiring": "popular_commander", "charismatic": "charismatic", "glory_hound": "ambitious",
    "choleric": "wrathful", "deeply_religious": "pious", "clever": "innovative", "intuitive": "innovative",
    "arrogant": "arrogant", "diplomatic": "tactful", "tactful": "tactful", "bigoted": "bigoted",
    "maladroit": "inept", "romantic": "romantic", "careful": "cautious", "stalwart": "stalwart_defender",
    "heroic": "brave", "stout": "brave", "spirited": "brave", "keen": "meticulous",
    "resourceful": "resupply_commander", "skilled": "basic_offensive_planner",
}
BACKGROUND = {
    "war_college": "basic_offensive_planner", "cavalry_school": "basic_cavalry_commander",
    "drillmaster": "basic_defensive_strategist", "innovative_tactician": "innovative", "engineer": "engineer",
    "cartographer": "surveyor", "expert_raider": "pillager", "old_school": "traditionalist_commander",
    "elderly": "elder", "disgraced": "scandalous", "corrupt": "grifter", "unqualified": "inexperienced",
    "politician": "basic_political_operator", "diplomat": "basic_diplomat",
    "gifted_administrator": "master_bureaucrat", "natural_born_leader": "popular_commander",
}
valid = set()
for f in (V3 / "common/character_traits").glob("*.txt"):
    valid |= set(re.findall(r"^(\w+)\s*=\s*\{", f.read_text(encoding="utf-8-sig"), re.M))

out = ["# Generated by tools/vic3_characters.py from the Vic2 mod's starting leaders (history/units).", "CHARACTERS = {"]
n = collections.Counter()
for f in sorted((V2 / "history/units").glob("*.txt")):
    tag = f.name[:3]
    if tag not in dod_cap:
        continue
    for m in re.finditer(r"leader\s*=\s*\{(.*?)\}", f.read_text(encoding="latin-1"), re.S):
        b = m.group(1)
        name = re.search(r'name\s*=\s*"([^"]+)"', b)
        if not name:
            continue
        kind = (re.search(r"type\s*=\s*(\w+)", b) or [None, "land"])[1]
        parts = name.group(1).replace('"', "").split()
        first, last = parts[0], " ".join(parts[1:]) or parts[0]
        traits = []
        for key, table in (("personality", PERSONALITY), ("background", BACKGROUND)):
            v = re.search(key + r"\s*=\s*(\w+)", b)
            tr = table.get(v.group(1)) if v else None
            if tr in valid and tr not in traits:
                traits.append(tr)
        if kind == "sea" and "basic_naval_commander" not in traits:
            traits.insert(0, "basic_naval_commander")
        noble = "yes" if re.search(r"background\s*=\s*aristocrat", b) else "no"
        role = "is_admiral" if kind == "sea" else "is_general"
        out += [f"\tc:{tag} ?= {{", "\t\tcreate_character = {", f'\t\t\tfirst_name = "{first}"', f'\t\t\tlast_name = "{last}"',
                "\t\t\thistorical = yes", f"\t\t\tnoble = {noble}", "\t\t\tbirth_date = 1796.1.1", f"\t\t\t{role} = yes",
                "\t\t\tcommander_rank = default", "\t\t\tinterest_group = ig_armed_forces",
                "\t\t\ttraits = { " + " ".join(traits) + " }", "\t\t}", "\t}"]
        n[role] += 1
out.append("}")
(OUTDIR / "dod_commanders.txt").write_text("\n".join(out) + "\n", encoding="utf-8-sig")
print(f"vanilla tags kept: {len(keep)} ({kept_blocks} character blocks); hand-written DoD rulers: {len(hand)}")
print(f"commanders: {dict(n)}")
