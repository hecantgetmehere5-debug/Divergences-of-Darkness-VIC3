"""Starting technology, armies and fleets for every DoD country.

Technology: each country gets the vanilla tech tier (1 = most advanced, 7 = least) of the
vanilla country that owned its capital in 1836. Countries vanilla already gives techs to
(same tag in vanilla history/countries) are left alone.
Armies: one army at the capital, sized by population, with a unit mix that depends on tier.
Fleets: countries with a naval administration get a fleet based at their largest naval
administration, sized by its levels.

Run after tools/vic3_start_setup.py and before tools/vic3_economy.py (which sizes barracks
from these armies). Usage: py tools/vic3_military.py <vic3_game_dir>
Writes DoD_Vic3/common/history/military_formations/00_dod_armies.txt and
       DoD_Vic3/common/history/countries/dod_01_technology.txt
"""
import collections, re, sys
from pathlib import Path

V3 = Path(sys.argv[1])
ROOT = Path(__file__).resolve().parent.parent
MOD = ROOT / "DoD_Vic3"

# vanilla tier per tag, and vanilla owner per state
# vanilla_tier: vanilla's own tiers (to look up the 1836 owner of a capital)
# vtier: tags that still get vanilla's techs in DoD (vanilla history not removed by
#        tools/fix_tag_collisions.py) - these are left alone
vanilla_tier, vtier = {}, {}
for f in (V3 / "common/history/countries").glob("*.txt"):
    over = MOD / "common/history/countries" / f.name
    for t, table in ((f.read_text(encoding="utf-8-sig"), vanilla_tier),
                     ((over if over.exists() else f).read_text(encoding="utf-8-sig"), vtier)):
        for m in re.finditer(r"c:(\w+)\s*\??=\s*\{", t):
            tm = re.search(r"effect_starting_technology_tier_(\d)_tech", t[m.end():m.end() + 4000])
            if tm and m.group(1) not in table:
                table[m.group(1)] = int(tm.group(1))
vowner = {}
t = (V3 / "common/history/states/00_states.txt").read_text(encoding="utf-8-sig")
for m in re.finditer(r"s:(STATE_\w+)\s*=\s*\{(.*?)\n\t\}", t, re.S):
    best = max(((len(p.split()), c) for c, p in re.findall(r"country\s*=\s*c:(\w+)\s*owned_provinces\s*=\s*\{([^}]*)\}", m.group(2))), default=None)
    if best:
        vowner[m.group(1)] = best[1]

strat = {}
for f in (V3 / "common/strategic_regions").glob("*.txt"):
    for m in re.finditer(r"^(region_\w+)\s*=\s*\{.*?states\s*=\s*\{([^}]*)\}", f.read_text(encoding="utf-8-sig"), re.S | re.M):
        for s in m.group(2).split():
            strat[s] = m.group(1)

# DoD data
cd = (MOD / "common/country_definitions/dod_countries.txt").read_text(encoding="utf-8-sig")
capital = {m.group(1): c.group(1) for m in re.finditer(r"^(\w{3}) = \{(.*?)^\}", cd, re.S | re.M)
           if (c := re.search(r"^\s*capital = (STATE_\w+)", m.group(2), re.M))}
tag_pop = collections.Counter()
t = (MOD / "common/history/pops/00_dod_pops.txt").read_text(encoding="utf-8-sig")
for r in re.finditer(r"region_state:(\w+) = \{(.*?)\n\t\t\}", t, re.S):
    tag_pop[r.group(1)] += sum(int(x) for x in re.findall(r"size = (\d+)", r.group(2)))
# naval administration per tag and state (from the current buildings file)
navadm = collections.defaultdict(collections.Counter)
t = (MOD / "common/history/buildings/00_dod_buildings.txt").read_text(encoding="utf-8-sig")
for m in re.finditer(r"s:(STATE_\w+) = \{(.*?)\n\t\}", t, re.S):
    for r in re.finditer(r"region_state:(\w+) = \{(.*?)\n\t\t\}", m.group(2), re.S):
        for lv in re.findall(r'"building_naval_administration"\s*add_ownership = \{ country = \{ country = "c:\w+" levels = (\d+)', r.group(2)):
            navadm[r.group(1)][m.group(1)] += int(lv)

tier = {}
for tg, st in capital.items():
    tier[tg] = vtier.get(tg) or vanilla_tier.get(vowner.get(st), 5)

# ---------- technology ----------
out = ["# Generated by tools/vic3_military.py: starting tech tier = vanilla tier of the 1836 owner of the capital.",
       "COUNTRIES = {"]
for tg in sorted(tier):
    if tg in vtier:
        continue
    out.append(f"\tc:{tg} ?= {{ effect_starting_technology_tier_{tier[tg]}_tech = yes }}")
out.append("}")
(MOD / "common/history/countries/dod_01_technology.txt").write_text("\n".join(out) + "\n", encoding="utf-8-sig")

# ---------- armies and fleets ----------
MIX = {  # tier -> [(unit, share)]
    1: [("line_infantry", .7), ("dragoons", .15), ("cannon_artillery", .15)],
    2: [("line_infantry", .7), ("dragoons", .15), ("cannon_artillery", .15)],
    3: [("line_infantry", .7), ("dragoons", .2), ("cannon_artillery", .1)],
    4: [("irregular_infantry", .75), ("hussars", .15), ("cannon_artillery", .1)],
}
LOW = [("irregular_infantry", .85), ("hussars", .15)]


def split(n, mix):
    counts = [(u, int(n * s)) for u, s in mix]
    counts[0] = (counts[0][0], counts[0][1] + n - sum(c for _, c in counts))
    return [(u, c) for u, c in counts if c > 0]


out = ["# Generated by tools/vic3_military.py: one army per country at its capital, plus a fleet for naval powers.",
       "MILITARY_FORMATIONS = {"]
fleets = ships_total = 0
for tg in sorted(capital):
    st = capital[tg]
    if st not in strat or not tag_pop[tg]:
        continue
    n = max(1, min(60, round(tag_pop[tg] / 1.5e6)))
    out += [f"\tc:{tg} ?= {{", "\t\tcreate_military_formation = {", "\t\t\ttype = army", f"\t\t\thq_region = sr:{strat[st]}"]
    for u, c in split(n, MIX.get(tier[tg], LOW)):
        out += ["\t\t\tcombat_unit = {", f"\t\t\t\ttype = unit_type:combat_unit_type_{u}",
                f"\t\t\t\tstate_region = s:{st}", f"\t\t\t\tcount = {c}", "\t\t\t}"]
    out.append("\t\t}")
    if navadm[tg]:
        base, lv = navadm[tg].most_common(1)[0]
        total = min(40, sum(navadm[tg].values()))
        if base in strat and total:
            lines = total // 4 if tier[tg] <= 2 else 0
            out += ["\t\tcreate_military_formation = {", "\t\t\ttype = fleet", f"\t\t\thq_region = sr:{strat[base]}"]
            for ship, c in (("ship_of_the_line", lines), ("frigate", total - lines)):
                if c:
                    out += ["\t\t\tship = {", f"\t\t\t\ttype = ship_type:ship_type_{ship}", f"\t\t\t\tcount = {c}", "\t\t\t}"]
            out.append("\t\t}")
            fleets += 1
            ships_total += total
    out.append("\t}")
out.append("}")
(MOD / "common/history/military_formations/00_dod_armies.txt").write_text("\n".join(out) + "\n", encoding="utf-8-sig")
print(f"tech set for {sum(1 for t in tier if t not in vtier)} countries; tiers: {sorted(collections.Counter(tier.values()).items())}")
print(f"armies: {len(capital)}  fleets: {fleets}  ships: {ships_total}")
