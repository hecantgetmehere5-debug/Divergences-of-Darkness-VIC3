"""Rebuild the DoD cultures in the Vic3 1.13 culture layout.

Each DoD culture copies its closest vanilla culture (heritage, language, traditions,
obsessions, names, graphics, ethnicities) and keeps its own colour and religion. DoD
cultures that share a name with a vanilla culture are dropped, so vanilla's definition is used.

Usage: py tools/fix_cultures.py <vic3_game_dir>
"""
import re, sys
from pathlib import Path

V3 = Path(sys.argv[1])
FILE = Path(__file__).resolve().parent.parent / "DoD_Vic3/common/cultures/dod_cultures.txt"
PARENT = {
    "anglois": "french", "provencal": "occitan", "rheinish": "north_german", "burgundian": "wallonian",
    "scandinavian": "swedish", "livlandian": "north_german", "vinlander": "norwegian", "septiman": "wallonian",
    "plantagenian": "british", "athesian": "north_italian", "afro_germanic": "afro_caribbean",
    "rohnnst": "algonquian", "lotharian": "wallonian", "beornian": "british", "guianan": "dutch",
    "granadan": "colombian", "lusitanian": "brazilian", "ayitian": "afro_caribbean",
    "afro_latino": "afro_caribeno", "qingqiuan": "han", "ganguan": "han", "kaiganese": "japanese",
    "beifaren": "han", "nanfaren": "yue", "tionghoa": "min", "afro_south_african": "griqua",
    "khaliji": "bedouin", "kunok": "bosniak", "amazonian_native": "amazonic",
}


def blocks(text):
    for m in re.finditer(r"^(\w+)\s*=\s*\{", text, re.M):
        i, d = m.end(), 1
        while d:
            d += {"{": 1, "}": -1}.get(text[i], 0)
            i += 1
        yield m.group(1), text[m.start():i]


vanilla = dict(b for f in (V3 / "common/cultures").glob("*.txt") for b in blocks(f.read_text(encoding="utf-8-sig")))
src = FILE.read_text(encoding="utf-8-sig")
out = ["# Divergences of Darkness: cultures that do not exist in vanilla Victoria 3.",
       "# Generated by tools/fix_cultures.py: each copies its closest vanilla culture and keeps its own colour and religion.", ""]
dropped = []
for name, body in blocks(src):
    if name in vanilla:
        dropped.append(name)
        continue
    parent = PARENT[name]
    color = re.search(r"color\s*=\s*(rgb)?\s*\{[^}]*\}", body).group(0)
    religion = re.search(r"religion\s*=\s*(\w+)", body).group(1)
    comment = re.match(r"\w+ = \{\s*(#[^\n]*)?", body).group(1) or ""
    new = re.sub(rf"^{parent}\s*=\s*\{{", f"{name} = {{  {comment}  (based on {parent})", vanilla[parent], count=1)
    new = re.sub(r"color\s*=\s*(rgb)?\s*\{[^}]*\}", color, new, count=1)
    new = re.sub(r"religion\s*=\s*\w+", f"religion = {religion}", new, count=1)
    out += [new, ""]
FILE.write_text("\n".join(out), encoding="utf-8-sig")
print("rebuilt:", len(PARENT) - 0, "dropped (vanilla has them):", dropped)
