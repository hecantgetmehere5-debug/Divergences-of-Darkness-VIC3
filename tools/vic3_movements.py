"""Build the DoD political movements from the closest vanilla movement.

Each DoD movement copies a vanilla movement's full definition (so ideologies, support
weights and civil-war rules stay valid) and swaps in its own creation trigger and, for
cultural movements, which culture it can pick.

Usage: py tools/vic3_movements.py <vic3_game_dir>
Writes DoD_Vic3/common/political_movements/dod_movements.txt and its English localisation.
"""
import re, sys
from pathlib import Path

V3 = Path(sys.argv[1])
MOD = Path(__file__).resolve().parent.parent / "DoD_Vic3"

MOVEMENTS = [
    # key, vanilla base, name, description, creation trigger (root = country), culture selection (root = culture)
    ("movement_dod_parishers", "movement_liberal", "Parishers",
     "Beornians who want every parish to govern itself, against the bishops and the absolute King.",
     "OR = { c:NAN ?= this c:HBE ?= this }", None),
    ("movement_dod_arcadianism", "movement_cultural_majority", "Arcadianism",
     "One Union for all the Arcadian peoples, free of the colonial powers.",
     "OR = { c:NBG ?= this c:PLA ?= this c:VIN ?= this }",
     "OR = { this = cu:vinlander this = cu:septiman this = cu:plantagenian }"),
    ("movement_dod_sons_of_harold", "movement_cultural_minority", "Sons of Harold",
     "English nationalists who will not bow to the Anglois Crown.",
     "c:DUA ?= this", "this = cu:british"),
    ("movement_dod_sons_of_saint_louis", "movement_cultural_minority", "Sons of Saint Louis",
     "French and Provencal nationalists within the Dual Monarchy.",
     "c:DUA ?= this", "OR = { this = cu:french this = cu:occitan }"),
    ("movement_dod_carbonari", "movement_radical", "Carbonari",
     "The revolutionary secret society Etruria spread across Italy.",
     "OR = { country_has_primary_culture = cu:north_italian country_has_primary_culture = cu:south_italian }\n\t\tNOT = { has_law = law_type:law_parliamentary_republic }",
     None),
]


def block(text, key):
    m = re.search(rf"^{key}\s*=\s*\{{", text, re.M)
    i, depth = m.end(), 1
    while depth:
        depth += {"{": 1, "}": -1}.get(text[i], 0)
        i += 1
    return text[m.start():i]


def replace_field(body, field, inner):
    m = re.search(rf"^\t{field}\s*=\s*\{{", body, re.M)
    new = f"\t{field} = {{\n\t\t{inner}\n\t}}"
    if not m:  # insert after creation_trigger
        c = re.search(r"^\tcreation_trigger = \{.*?^\t\}", body, re.S | re.M)
        return body[:c.end()] + "\n" + new + body[c.end():]
    i, depth = m.end(), 1
    while depth:
        depth += {"{": 1, "}": -1}.get(body[i], 0)
        i += 1
    return body[:m.start()] + new + body[i:]


vanilla = "".join(f.read_text(encoding="utf-8-sig") for f in sorted((V3 / "common/political_movements").glob("*.txt")))
out = ["# Generated by tools/vic3_movements.py: DoD movements built on the closest vanilla movement.", ""]
loc = ["﻿l_english:"]
for key, base, name, desc, trigger, culture in MOVEMENTS:
    b = block(vanilla, base)
    b = re.sub(rf"^{base}\b", key, b)
    b = b.replace(f"is_political_movement_type = {base}", f"is_political_movement_type = {key}")
    b = replace_field(b, "creation_trigger", trigger)
    if culture:
        b = replace_field(b, "culture_selection_trigger", culture)
    out += [b, ""]
    loc += [f' {key}: "{name}"', f' {key}_short: "{name}"', f' {key}_name: "{name}"',
            f' {key}_desc: "{desc}"', f' {key}_icon: "@{base}!"']
(MOD / "common/political_movements").mkdir(exist_ok=True)
(MOD / "common/political_movements/dod_movements.txt").write_text("\n".join(out), encoding="utf-8-sig")
(MOD / "localization/english/dod_movements_l_english.yml").write_text("\n".join(loc) + "\n", encoding="utf-8")
print("movements:", len(MOVEMENTS))
