"""Put the attackers' armies on the front of each starting war, mobilised (like vanilla does
for Texas and Mexico).

For each war below it finds, on the Vic3 province map, a province owned by the attacker that
touches one owned by the defender (preferring the foothold state if one is given) and teleports
the attacker's armies to that front at game start.

Run after tools/vic3_start_setup.py. Usage: py tools/vic3_deployments.py <vic3_game_dir>
Writes DoD_Vic3/common/history/military_deployments/00_dod_deployments.txt
"""
import collections, re, sys
from pathlib import Path
import numpy as np
from PIL import Image

V3 = Path(sys.argv[1])
MOD = Path(__file__).resolve().parent.parent / "DoD_Vic3"
Image.MAX_IMAGE_PIXELS = None

# attacker, defender, preferred state for the front (or None). One deployment per attacker.
WARS = [
    ("SPA", "CLM", "STATE_ZULIA"),   # Colombian War of Independence (Maracaibo foothold)
    ("JAP", "KOR", "STATE_BUSAN"),   # Joseon Fight for Freedom
    ("TUR", "EGY", None),            # Egyptian Uprising
    ("AMT", "ETH", None),            # Ethiopian Civil War
    ("TNG", "MIG", None),            # Phoenix Invasion
]

owner, state_of = {}, {}
t = (MOD / "common/history/states/00_dod_states.txt").read_text(encoding="utf-8-sig")
for m in re.finditer(r"s:(STATE_\w+) = \{(.*?)\n\t\}", t, re.S):
    for tag, ps in re.findall(r"country = c:(\w+)\s*owned_provinces = \{([^}]*)\}", m.group(2)):
        for h in ps.split():
            owner[h.upper().replace("X", "x", 1)] = tag
            state_of[h.upper().replace("X", "x", 1)] = m.group(1)

img = np.asarray(Image.open(V3 / "map_data/provinces.png").convert("RGB"))
code = (img[..., 0].astype(np.uint32) << 16) | (img[..., 1].astype(np.uint32) << 8) | img[..., 2]
pairs = set()
for a, b in ((code[:, :-1], code[:, 1:]), (code[:-1, :], code[1:, :])):
    d = a != b
    for x, y in set(zip(a[d].tolist(), b[d].tolist())):
        pairs.add((x, y))
        pairs.add((y, x))
nbr = collections.defaultdict(set)
for x, y in pairs:
    nbr["x%06X" % x].add("x%06X" % y)

out = ["# Generated by tools/vic3_deployments.py: attackers start mobilised on the front of their war.",
       "MILITARY_DEPLOYMENTS = {"]
for att, dfd, pref in WARS:
    cands = [h for h, o in owner.items() if o == att and any(owner.get(n) == dfd for n in nbr[h])]
    if not cands:
        print(f"{att} vs {dfd}: no shared border, no deployment")
        continue
    cands.sort(key=lambda h: (state_of[h] != pref, h))
    p = cands[0]
    out += [f"\tc:{att} ?= {{  # vs {dfd}, front at {state_of[p]}",
            "\t\tevery_military_formation = {", "\t\t\tlimit = { is_army = yes }",
            "\t\t\tfully_mobilize_army = yes", f"\t\t\tteleport_to_front = p:{p}.front", "\t\t}", "\t}"]
    print(f"{att} vs {dfd}: front at {p} in {state_of[p]} ({len(cands)} border provinces)")
out.append("}")
d = MOD / "common/history/military_deployments"
d.mkdir(parents=True, exist_ok=True)
(d / "00_dod_deployments.txt").write_text("\n".join(out) + "\n", encoding="utf-8-sig")
