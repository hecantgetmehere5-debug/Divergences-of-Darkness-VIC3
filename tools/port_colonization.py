"""Port the Vic2 DoD frontier claim decisions (decisions/Divergences colonization.txt).

Each Vic2 decision lets one country claim a frontier region given as Vic2 province IDs. Those
IDs are mapped to Vic3 states through start_data/vic3_province_link.csv; the Vic3 decision
claims every state the region covers, which makes colonising or conquering it legitimate.

Usage: py tools/port_colonization.py <vic2_mod_dir>
Writes DoD_Vic3/common/decisions/dod_col_decisions.txt and localization/english/dod_col_l_english.yml
"""
import collections, csv, re, sys
from pathlib import Path

V2 = Path(sys.argv[1])
ROOT = Path(__file__).resolve().parent.parent
MOD = ROOT / "DoD_Vic3"
rd = lambda p: p.read_bytes().decode("cp1252", "replace")

loc = {}
for f in sorted((V2 / "localisation").glob("*.csv")):
    for l in rd(f).splitlines():
        p = l.split(";")
        if len(p) > 1 and p[0].strip() and p[0].strip() not in loc:
            loc[p[0].strip()] = re.sub("§.", "", p[1]).strip().replace("\\n", " ")

prov2states = collections.defaultdict(collections.Counter)
for r in csv.DictReader(open(ROOT / "start_data/vic3_province_link.csv", encoding="utf-8")):
    if r["vic2_province"] != "0":
        prov2states[int(r["vic2_province"])][r["state"]] += 1
# Vic2 named regions (NA_1 = { 1 2 3 }) used by the decisions
regions = {k: [int(x) for x in v.split()] for k, v in re.findall(r"^\s*(\w+)\s*=\s*\{([\d\s]*)\}", re.sub(r"#[^\n]*", "", rd(V2 / "map/region.txt")), re.M)}
tags = set(re.findall(r"^(\w{3}) = \{", (MOD / "common/country_definitions/dod_countries.txt").read_text(encoding="utf-8-sig"), re.M))

text = re.sub(r"#[^\n]*", "", rd(V2 / "decisions/Divergences colonization.txt"))
decisions, depth, cur, start = [], 0, None, 0
for m in re.finditer(r"([\w.]+)\s*=\s*\{|\{|\}", text):
    if m.group(0) == "}":
        depth -= 1
        if depth == 1 and cur:
            decisions.append((cur, text[start:m.end()]))
            cur = None
    else:
        if m.group(1) and depth == 1:
            cur, start = m.group(1), m.start()
        depth += 1

out = ["﻿# Generated by tools/port_colonization.py from the Vic2 mod's frontier claim decisions."]
lo = ["﻿l_english:"]
skipped = []
for key, body in decisions:
    pot = re.search(r"potential\s*=\s*\{(.*?)\n\s{8}\}", body, re.S)
    who = sorted(set(re.findall(r"\btag\s*=\s*([A-Z]{3})", pot.group(1) if pot else body)) & tags)
    eff = re.search(r"effect\s*=\s*\{(.*)", body, re.S).group(1)
    provs = {int(x) for x in re.findall(r"\b(\d{2,4})\s*=\s*\{", eff)} | {int(x) for x in re.findall(r"province\s*=\s*(\d+)", eff)}
    for reg in re.findall(r"\b([A-Za-z]\w*)\s*=\s*\{\s*secede_province", eff):
        provs |= set(regions.get(reg, []))
    states = sorted({prov2states[p].most_common(1)[0][0] for p in provs if prov2states[p]})
    if not states:
        skipped.append(key)
        continue
    shown = ("OR = { " + " ".join(f"c:{t} ?= this" for t in who) + " }") if who else "always = yes"
    k = f"dod_col_{key.lower()}"
    claims = "\n\t\t".join(f"s:{s} = {{ add_claim = root }}" for s in states)
    out.append(f"""
{k} = {{
	is_shown = {{
		{shown}
		NOT = {{ has_variable = {k} }}
	}}
	possible = {{
		is_at_war = no
	}}
	when_taken = {{
		set_variable = {k}
		{claims}
	}}
	ai_chance = {{ value = 40 }}
}}""")
    title = loc.get(f"{key}_title", key.replace("_", " ").title()).replace('"', "'")
    desc = loc.get(f"{key}_desc", "").replace('"', "'")
    lo += [f' {k}:0 "{title}"', f' {k}_desc:0 "{desc}"']

(MOD / "common/decisions/dod_col_decisions.txt").write_text("\n".join(out) + "\n", encoding="utf-8")
(MOD / "localization/english/dod_col_l_english.yml").write_text("\n".join(lo) + "\n", encoding="utf-8")
print(f"decisions: {len(decisions) - len(skipped)}; skipped (no Vic3 state found): {skipped}")
